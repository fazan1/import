-- =====================================================================
-- TRADE FINDER (v129) — the Lanka Trade Finder tool, now inside the CRM (Tools -> Trade Finder)
--   trade_businesses      : the company directory (name, type, category, address, phone, district)
--   trade_contacts        : who you called / WhatsApped, status, note, staff member
--   trade_saved_searches  : recent searches, tuned products, saved AI results (so AI is not paid twice)
-- Logged-in CRM users only (same "members only" rule as every table). Not split by book.
-- Nothing is deleted. Safe to re-run. Run on your MAIN project only.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.trade_businesses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  type text,
  cat text,
  addr text,
  phone text,
  district text,
  source text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS trade_businesses_name_idx ON public.trade_businesses (lower(name));

CREATE TABLE IF NOT EXISTS public.trade_contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_name text NOT NULL,
  channel text,
  product text,
  status text,
  note text,
  handler text,
  contacted_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS trade_contacts_when_idx ON public.trade_contacts (contacted_at DESC);

CREATE TABLE IF NOT EXISTS public.trade_saved_searches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query text NOT NULL,
  kind text NOT NULL,
  district text NOT NULL DEFAULT '',
  results jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS trade_saved_searches_q_idx ON public.trade_saved_searches (kind, query, district);

-- "updated" time moves when status / note / staff changes (follow-up reminders use it)
CREATE OR REPLACE FUNCTION public.trade_contacts_touch() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_trade_contacts_touch ON public.trade_contacts;
CREATE TRIGGER trg_trade_contacts_touch BEFORE UPDATE ON public.trade_contacts
  FOR EACH ROW EXECUTE FUNCTION public.trade_contacts_touch();

-- security: logged-in, active CRM users only; the public key gets nothing
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['trade_businesses', 'trade_contacts', 'trade_saved_searches'] LOOP
    EXECUTE format('REVOKE ALL ON public.%I FROM anon', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "open all" ON public.%I', t);
    EXECUTE format('CREATE POLICY "open all" ON public.%I FOR ALL TO authenticated USING (true) WITH CHECK (true)', t);
    IF to_regprocedure('public.is_app_member()') IS NOT NULL THEN
      EXECUTE format('DROP POLICY IF EXISTS "members only" ON public.%I', t);
      EXECUTE format('CREATE POLICY "members only" ON public.%I AS RESTRICTIVE FOR ALL TO anon, authenticated USING ((SELECT public.is_app_member())) WITH CHECK ((SELECT public.is_app_member()))', t);
    END IF;
  END LOOP;
END $$;

NOTIFY pgrst, 'reload schema';

SELECT (SELECT count(*) FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
        WHERE c.relname IN ('trade_businesses', 'trade_contacts', 'trade_saved_searches') AND p.polname = 'members only') AS locked_tables,
       (SELECT count(*) FROM public.trade_businesses) AS companies,
       'trade finder ready' AS status;
